#!/usr/bin/env python3
"""Generate the compiler's intrinsic table from spec/uisa.yaml.

Every uisa instruction that is not millicode control flow becomes a C-callable
intrinsic `__<mnemonic with '.' -> '_'>` (add.8z -> __add_8z, ld.32.gd ->
__ld_32_gd). The table also carries the immediate ranges and register indices
the back end needs, so nothing about the ISA is hand-maintained in C++.

usage: gen_intrinsics.py OUT.inc
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "tools"))
import uisa  # noqa: E402

# Entry-ABI values of the `insn` entry point, by the register the spec puts them in.
ENTRY_NAMES = {"x1": "opword", "x2": "ext01", "x3": "ext23", "x4": "next_pc"}

# Millicode control flow is generated by the compiler, never called directly.
COMPILER_ONLY = {"jump", "jump_ind", "call", "branch", "ret"}
# Ops after which control never comes back to the next instruction.
NORETURN_CTI = {"gexit", "gfault"}
NORETURN_NAMES = {"halt", "brk"}

# Base ops the back end emits itself; checked to exist.
BACKEND_OPS = ["add", "sub", "and", "or", "xor", "sll", "srl", "sra", "slt", "sltu", "mul",
               "div", "divu", "rem", "remu", "sext8", "sext16", "zext8", "zext16",
               "addi", "andi", "ori", "xori", "slli", "srli", "srai", "slti", "sltiu", "lui",
               "jal", "call", "ret", "b.eq", "b.ne", "b.lt", "b.ge", "b.ltu", "b.geu", "rdg", "wrg"]


def imm_range(spec, v):
    signed, scale = spec.imm_info(v)
    f = v.fmt.fields["imm"]
    lo, hi = ((-(1 << (f.width - 1)), (1 << (f.width - 1)) - 1) if signed else (0, (1 << f.width) - 1))
    if v.imm_max is not None:
        hi = min(hi, v.imm_max)
    return lo * scale, hi * scale, scale


def describe(spec, v):
    """-> (args, template, has_result, tied_arg, imm ranges per arg) or None."""
    cti = v.attrs.get("cti")
    if cti in COMPILER_ONLY:
        return None
    if v.mnemonic in ("lui", "auipc"):
        return None
    if v.kind in ("cas", "mov16"):                # PLA-only (68k CAS, MOVE16); millicode uses ldl/stu
        return None
    args, rng, tmpl = [], [], []
    has_result = spec.writes_rd(v)
    tied = -1
    fpf = spec.fp_fields(v)
    if fpf:
        # FP ops: an FP register operand is a constant (the register number,
        # printed as fN); the FP register file is not allocated, so every FP
        # op is ordered (side effects) unless it only reads FP registers into
        # an x register result
        nfp = len(spec.fp_regs)
        for op in v.operands:
            if op in fpf:
                tmpl.append("f%%%d" % len(args))
                args.append("i")
                rng.append((0, nfp - 1, 1))
            elif op == "rd":
                tmpl.append("%d")
            else:
                tmpl.append("%%%d" % len(args))
                args.append("v")
                rng.append((0, 0, 1))
        return args, tmpl, spec.writes_int_rd(v), -1, rng

    def add_arg(kind, r=(0, 0, 1)):
        args.append(kind)
        rng.append(r)
        return len(args) - 1

    # an address argument's range is the displacement the instruction takes
    # (12 bits for plain loads and stores, 10 for probes, 9 for ld.c / st.c)
    if v.kind in ("load", "probe"):
        a = add_arg("m", imm_range(spec, v))
        tmpl = ["%d", "%%m%d" % a]
    elif v.kind == "store" and not v.attrs.get("writeback"):
        a = add_arg("m", imm_range(spec, v))
        d = add_arg("v")
        tmpl = ["%%%d" % d, "%%m%d" % a]
    elif v.kind == "store":                       # base-register writeback
        b = add_arg("t")
        tied = b
        d = add_arg("v")
        lo, hi, sc = imm_range(spec, v)
        i = add_arg("i", (lo, hi, sc))
        tmpl = ["%%%d" % d, "%%%d(%%d)" % i]
    else:
        if v.tied or v.attrs.get("reads_rd"):
            tied = add_arg("t")                     # the old rd value
        for op in v.operands:
            if op == "rd":
                tmpl.append("%d")
            elif op in ("rs1", "rs2"):
                tmpl.append("%%%d" % add_arg("v"))
            elif op == "imm":
                tmpl.append("%%%d" % add_arg("i", imm_range(spec, v)))
            elif op == "csr":
                tmpl.append("%%%d" % add_arg("i", (0, 255, 1)))
            elif op in ("off", "wid"):
                tmpl.append("%%%d" % add_arg("i", (0, 32, 1)))
            else:
                raise SystemExit("gen_intrinsics: %s: operand %s" % (v.mnemonic, op))
        if v.kind == "guest" and v.gform == "compare":
            has_result = False
    return args, tmpl, has_result, tied, rng


def lui_shift(spec):
    sem = spec.by_mnemonic["lui"].sem
    if "b << " not in sem:
        raise SystemExit("gen_intrinsics: cannot read the lui shift from %r" % sem)
    return int(sem.split("b << ")[1].rstrip(";"))


def main():
    out = sys.argv[1]
    spec = uisa.load()
    for m in BACKEND_OPS:
        if m not in spec.by_mnemonic:
            raise SystemExit("gen_intrinsics: back end needs %s, not in the spec" % m)
    rows = []
    for v in spec.variants:
        d = describe(spec, v)
        if d is None:
            continue
        args, tmpl, has_result, tied, rng = d
        cti = v.attrs.get("cti")
        noreturn = cti in NORETURN_CTI or v.mnemonic in NORETURN_NAMES
        side = (not has_result or bool(v.attrs.get("writes_flags")) or v.kind in ("load", "store", "probe")
                or v.attrs.get("serialize") or v.attrs.get("store_bytes") or cti is not None or noreturn
                or ("rd" in spec.fp_fields(v)))
        name = "__" + v.mnemonic.replace(".", "_")
        asm = v.mnemonic + ((" " + ", ".join(tmpl)) if tmpl else "")
        argr = ", ".join("{%d, %d, %d}" % r for r in rng) or "{0, 0, 1}"
        rows.append('  {"%s", "%s", "%s", %d, %d, %d, %d, %d, {%s}},' % (
            name, asm, "".join(args), int(has_result), tied, int(bool(side)), int(noreturn),
            int(bool(v.attrs.get("reads_flags") or v.attrs.get("writes_flags"))), argr))

    o = ["// Generated by compiler/gen_intrinsics.py from spec/uisa.yaml. Do not edit.",
         "// name, asm template, arg kinds (v value, i constant, m address, t tied old rd),",
         "// has_result, tied arg, side effects, noreturn, touches flags, {lo, hi, scale} per arg",
         "static const IntrinsicDesc INTRINSICS[] = {"]
    o += rows
    o.append("};")

    def rng_of(m):
        lo, hi, sc = imm_range(spec, spec.by_mnemonic[m])
        return lo, hi

    consts = []
    for i in range(8):
        consts.append(("D%d" % i, i))
        consts.append(("A%d" % i, 8 + i))
    consts.append(("GPC", spec.regs["gpc"] - 32))
    consts.append(("GSR", spec.regs["gsr"] - 32))
    for c in spec.csrs:
        consts.append(("CSR_" + c["name"].upper(), c["num"]))
    for k, b in spec.d["ccr_layout"].items():
        consts.append(("CCR_" + k, 1 << b))
    o.append("static const NamedConst SPEC_CONSTS[] = {")
    o += ['  {"%s", %d},' % kv for kv in consts]
    o.append("};")

    entry = next(e for e in spec.d["entry_points"] if e["name"] == "insn")
    o.append("static const EntryReg ENTRY_REGS[] = {")
    for reg in entry["regs"]:
        o.append('  {"__%s", %d},  // %s' % (ENTRY_NAMES[reg], spec.regs[reg], entry["regs"][reg]))
    o.append("};")

    o.append("static const char *const REG_NAMES[64] = {")
    o.append("  " + ", ".join('"%s"' % spec.reg_by_index.get(i, "") for i in range(64)))
    o.append("};")
    xc = next(c for c in spec.d["reg_classes"] if c.get("prefix") == "x")
    p = spec.params
    vals = {
        "CALL_STACK_DEPTH": p["call_stack_depth"],
        "NUM_XREGS": xc["count"],
        "GREG_BASE": spec.regs["d0"],
        "ADDI_LO": rng_of("addi")[0], "ADDI_HI": rng_of("addi")[1],
        "LOGI_HI": rng_of("andi")[1],
        "SHIFT_MAX": rng_of("slli")[1],
        "LUI_HI": rng_of("lui")[1],
        "LUI_SHIFT": lui_shift(spec),
        "MEM_LO": rng_of("ld.32.h")[0], "MEM_HI": rng_of("ld.32.h")[1],
        "BR_LO": rng_of("b.eq")[0], "BR_HI": rng_of("b.eq")[1],
        "JAL_LO": rng_of("jal")[0], "JAL_HI": rng_of("jal")[1],
    }
    for k, v in vals.items():
        o.append("static const int %s = %d;" % (k, v))
    with open(out, "w") as f:
        f.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()

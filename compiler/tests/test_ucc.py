#!/usr/bin/env python3
"""Test ucc.

t_*.c    run-time tests: compiled by ucc, assembled by tools/uisa.py and run on
         a uisa ISS (run.cc), and compiled natively against host.h; the two
         must agree on random guest states. The entry function is named after
         the file.
err_*.c  must fail to compile; the first line is `// expect: <text>` and the
         diagnostic must contain <text>.

usage: test_ucc.py [iterations [name-substring]]
"""

import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import uisa  # noqa: E402

UCC = os.path.join(ROOT, "build", "compiler", "ucc")
# the tests check correctness: everything at -O0 (greedy allocation), and a
# few call-heavy programs again at -O2 (z3, small budget) so that path is
# covered too
UCC_FLAGS = ["-O0"]
O2_FLAGS = ["-O2", "--rlimit", "30000000"]
O2_TESTS = ["t_calls", "t_u64call", "t_control"]
OUT = os.path.join(ROOT, "build", "ucc_tests")


def gen_relax():
    """A loop whose body is far larger than a compare-and-branch reaches."""
    lines = ["// generated by test_ucc.py: forces branch relaxation",
             "entry void t_relax(void) {",
             "  u32 x = __rdg(D0), y = __rdg(D1);",
             "  for (u32 i = 0; i < (y & 3); i++) {",
             "    if (x & 1) {"]
    for k in range(300):
        lines.append("      x = (x * %d + (x >> %d)) ^ (y + %d);" % (3 + 2 * (k % 7), 1 + k % 13, k))
    lines.append("    } else {")
    for k in range(300):
        lines.append("      x = (x * %d + (x << %d)) ^ (y - %d);" % (5 + 2 * (k % 5), 1 + k % 11, k))
    lines += ["    }", "    x += i;", "  }",
              "  __wrg(D2, x);", "  __wrg(GPC, __next_pc());", "  __gexit();", "}"]
    path = os.path.join(OUT, "t_relax.c")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path


def main():
    iters = sys.argv[1] if len(sys.argv) > 1 else "3000"
    only = sys.argv[2] if len(sys.argv) > 2 else ""
    os.makedirs(OUT, exist_ok=True)
    spec = uisa.load()
    fails = 0

    for src in sorted(glob.glob(os.path.join(HERE, "err_*.c"))) if not only else []:
        with open(src) as f:
            first = f.readline()
        m = re.match(r"//\s*expect:\s*(.*)", first)
        expect = m.group(1).strip() if m else "?"
        p = subprocess.run([UCC] + UCC_FLAGS + [src, "-o", os.devnull], capture_output=True, text=True)
        name = os.path.basename(src)
        if p.returncode == 0 or expect not in p.stderr:
            print("FAIL %s: expected an error containing %r, got (rc %d):\n%s" % (name, expect, p.returncode, p.stderr))
            fails += 1
        else:
            print("ucc error  %-14s ok: %s" % (name, p.stderr.strip().splitlines()[0]))

    srcs = sorted(glob.glob(os.path.join(HERE, "t_*.c"))) + [gen_relax()]
    srcs = [x for x in srcs if only in os.path.basename(x)]
    inc = []
    table = []
    for src in srcs:
        name = os.path.splitext(os.path.basename(src))[0]
        inc.append("namespace h_%s {\n#include \"%s\"\n}" % (name, src))
        for tag, flags in [("", UCC_FLAGS)] + ([("_O2", O2_FLAGS)] if name in O2_TESTS else []):
            asm = os.path.join(OUT, name + tag + ".s")
            if subprocess.call([UCC] + flags + [src, "-o", asm]) != 0:
                print("FAIL %s%s: does not compile" % (name, tag))
                fails += 1
                continue
            with open(asm) as f:
                words, labels = spec.assemble_program(f.read())
            if name not in labels:
                sys.exit("%s: no entry function named %s" % (src, name))
            img = "img_%s%s" % (name, tag)
            inc.append("static const uint32_t %s[] = {%s};" % (img, ", ".join("0x%08x" % w for w in words)))
            table.append('  {"%s%s", %s, %d, %d, h_%s::%s},' % (name, tag.replace("_", " -"), img, len(words),
                                                              labels[name] // 4, name, name))
    with open(os.path.join(OUT, "ucc_tests.inc"), "w") as f:
        f.write("// Generated by compiler/tests/test_ucc.py. Do not edit.\n")
        f.write("\n".join(inc) + "\n")
        f.write("static const UccTest TESTS[] = {\n" + "\n".join(table) + "\n};\n")
    exe = os.path.join(OUT, "run")
    cc = ["c++", "-std=c++17", "-O1", "-fwrapv", "-w", "-I" + os.path.join(ROOT, "build"), "-I" + HERE, "-I" + OUT,
          "-o", exe, os.path.join(HERE, "run.cc")]
    if subprocess.call(cc) != 0:
        sys.exit("test_ucc: the runner does not build")
    rc = subprocess.call([exe, iters])
    if fails or rc:
        print("test_ucc: FAILED")
        sys.exit(1)


if __name__ == "__main__":
    main()

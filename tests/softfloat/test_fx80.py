#!/usr/bin/env python3
"""Differential test of millicode/softfloat/softfloat.h against Previous's SoftFloat.

Compiles tests/softfloat/fx80_ops.c with ucc, assembles it, and builds
run_fx80.cc (the uisa ISS + Previous's softfloat.c). Previous's source is
found at $PREVIOUS_SRC (default ~/code/previous/src); without it the test is
skipped.

usage: test_fx80.py [iterations-per-op]
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import uisa  # noqa: E402

UCC = os.path.join(ROOT, "build", "compiler", "ucc")
OUT = os.path.join(ROOT, "build", "softfloat_tests")


def main():
    iters = sys.argv[1] if len(sys.argv) > 1 else "100000"
    prev = os.environ.get("PREVIOUS_SRC", os.path.expanduser("~/code/previous/src"))
    sf = os.path.join(prev, "softfloat")
    if not os.path.exists(os.path.join(sf, "softfloat.c")):
        print("test_fx80: skipped (no Previous source at %s; set PREVIOUS_SRC)" % prev)
        return
    os.makedirs(OUT, exist_ok=True)
    asm = os.path.join(OUT, "fx80_ops.s")
    flags = os.environ.get("UCCFLAGS", "-O0").split()
    if subprocess.call([UCC] + flags + [os.path.join(HERE, "fx80_ops.c"), "-o", asm]) != 0:
        sys.exit("test_fx80: ucc failed")
    spec = uisa.load()
    with open(asm) as f:
        words, labels = spec.assemble_program(f.read())
    with open(os.path.join(OUT, "fx80_image.inc"), "w") as f:
        f.write("// Generated by tests/softfloat/test_fx80.py. Do not edit.\n")
        f.write("static const uint32_t FX80_IMAGE[] = {%s};\n" % ", ".join("0x%08x" % w for w in words))
        f.write("static const int FX80_WORDS = %d;\n" % len(words))
        ents = [n for n in labels if n.startswith("fx80_") and "__" not in n]
        f.write("static const Entry FX80_ENTRIES[] = {%s};\n" %
                ", ".join('{"%s", %d}' % (n, labels[n] // 4) for n in sorted(ents)))
    sfo = os.path.join(OUT, "softfloat.o")
    if subprocess.call(["cc", "-c", "-O1", "-w", "-I" + sf, "-I" + os.path.join(prev, "includes"),
                        os.path.join(sf, "softfloat.c"), "-o", sfo]) != 0:
        sys.exit("test_fx80: Previous's softfloat.c does not build")
    exe = os.path.join(OUT, "run_fx80")
    if subprocess.call(["c++", "-std=c++17", "-O1", "-w", "-I" + os.path.join(ROOT, "build"),
                        "-I" + os.path.join(ROOT, "compiler", "tests"), "-I" + OUT, "-I" + sf,
                        os.path.join(HERE, "run_fx80.cc"), sfo, "-o", exe]) != 0:
        sys.exit("test_fx80: the runner does not build")
    print("softfloat: %d words of millicode" % len(words))
    if subprocess.call([exe, iters]) != 0:
        sys.exit("test_fx80: FAILED")


if __name__ == "__main__":
    main()

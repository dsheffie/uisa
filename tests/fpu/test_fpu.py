#!/usr/bin/env python3
"""Differential test of millicode/fpu.c against Previous's own FPU code.

Compiles millicode/fpu.c with ucc, assembles it, and builds run_fpu.cc (the
uisa ISS) with prev_fpu.c, Previous's cpu/fpp.c, cpu/fpp_softfloat.c and its
softfloat. Previous's source is $PREVIOUS_SRC (default ~/code/previous/src,
with config.h one directory up); the test is skipped if it is missing.

usage: test_fpu.py [ITERATIONS]
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, os.path.join(ROOT, "tools"))
import uisa  # noqa: E402

UCC = os.path.join(ROOT, "build", "compiler", "ucc")
OUT = os.path.join(ROOT, "build", "fpu_tests")


def main():
    iters = sys.argv[1] if len(sys.argv) > 1 else "100000"
    prev = os.environ.get("PREVIOUS_SRC", os.path.expanduser("~/code/previous/src"))
    if not os.path.exists(os.path.join(prev, "cpu", "fpp.c")):
        print("fpu: skipped (no Previous source at %s; set PREVIOUS_SRC)" % prev)
        return
    os.makedirs(OUT, exist_ok=True)
    asm = os.path.join(OUT, "fpu.s")
    flags = os.environ.get("UCCFLAGS", "-O0").split()
    if subprocess.call([UCC] + flags + [os.path.join(ROOT, "millicode", "fpu.c"), "-o", asm]) != 0:
        sys.exit("test_fpu: ucc failed")
    spec = uisa.load()
    with open(asm) as f:
        words, labels = spec.assemble_program(f.read())
    with open(os.path.join(OUT, "fpu_image.inc"), "w") as f:
        f.write("// Generated by tests/fpu/test_fpu.py. Do not edit.\n")
        f.write("static const uint32_t FPU_IMAGE[] = {%s};\n" % ", ".join("0x%08x" % w for w in words))
        f.write("static const int FPU_WORDS = %d;\n" % len(words))
        ents = [n for n in labels if "__" not in n]
        f.write("static const Entry FPU_ENTRIES[] = {%s};\n" %
                ", ".join('{"%s", %d}' % (n, labels[n] // 4) for n in sorted(ents)))

    inc = ["-I" + os.path.join(prev, ".."), "-I" + os.path.join(prev, "cpu"), "-I" + os.path.join(prev, "includes"),
           "-I" + os.path.join(prev, "softfloat"), "-I" + prev, "-I" + os.path.join(prev, "debug")]
    srcs = [os.path.join(prev, "cpu", "fpp.c"), os.path.join(prev, "cpu", "fpp_softfloat.c"),
            os.path.join(prev, "softfloat", "softfloat.c"), os.path.join(prev, "softfloat", "softfloat_fpsp.c"),
            os.path.join(prev, "softfloat", "softfloat_decimal.c"), os.path.join(HERE, "prev_fpu.c")]
    objs = []
    for src in srcs:
        obj = os.path.join(OUT, os.path.basename(src)[:-2] + ".o")
        if not os.path.exists(obj) or os.path.getmtime(obj) < os.path.getmtime(src):
            quiet = ["-include", os.path.join(HERE, "quiet.h")] if "/cpu/" in src else []
            if subprocess.call(["cc", "-c", "-O1", "-w"] + inc + quiet + [src, "-o", obj]) != 0:
                sys.exit("test_fpu: %s does not build" % src)
        objs.append(obj)
    exe = os.path.join(OUT, "run_fpu")
    if subprocess.call(["c++", "-std=c++17", "-O1", "-w", "-I" + os.path.join(ROOT, "build"),
                        "-I" + os.path.join(ROOT, "compiler", "tests"), "-I" + OUT, "-I" + HERE,
                        os.path.join(HERE, "run_fpu.cc")] + objs + ["-o", exe]) != 0:
        sys.exit("test_fpu: the runner does not build")
    print("fpu: %d words of millicode" % len(words), flush=True)
    if subprocess.call([exe, iters]) != 0:
        sys.exit("test_fpu: FAILED")


if __name__ == "__main__":
    main()

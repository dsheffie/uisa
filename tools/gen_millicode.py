#!/usr/bin/env python3
"""Assemble the millicode (millicode/*.s) and build its dispatch table.

Writes build/uisa_millicode.inc for the shadow model:
  MC_BASE            hidden-memory address of the image
  MC_IMAGE[]         the assembled words
  MC_ENTRY[65536]    per opword: byte offset of its routine, or -1
"""

import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import flows  # noqa: E402
import m68kdec  # noqa: E402
import uisa  # noqa: E402

ROOT = os.path.join(HERE, "..")


def main():
    with open(os.path.join(ROOT, "millicode", "dispatch.yaml")) as f:
        d = yaml.safe_load(f)
    text = ""
    for src in d["sources"]:
        with open(os.path.join(ROOT, "millicode", src)) as f:
            text += f.read() + "\n"
    spec = uisa.load()
    base = int(d.get("base", 0))
    words, labels = spec.assemble_program(text, base)
    ex = flows.Expander()
    entry = [-1] * 65536
    covered = {}
    for op in range(65536):
        fl = ex.expand(op)
        if fl.kind != "millicode":
            continue
        label = d["handlers"].get(fl.note)
        if label is None:
            continue
        if label not in labels:
            sys.exit("dispatch: no label %r" % label)
        entry[op] = labels[label] - base
        covered[fl.note] = covered.get(fl.note, 0) + 1
    o = ["// Generated by tools/gen_millicode.py from millicode/. Do not edit.",
         "static const uint32_t MC_BASE = 0x%x;" % base,
         "static const uint32_t MC_IMAGE[%d] = {" % len(words)]
    for i in range(0, len(words), 8):
        o.append("  " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    o.append("};")
    o.append("static const int32_t MC_ENTRY[65536] = {")
    for i in range(0, 65536, 32):
        o.append("  " + ",".join(str(x) for x in entry[i:i + 32]) + ",")
    o.append("};")
    with open(os.path.join(ROOT, "build", "uisa_millicode.inc"), "w") as f:
        f.write("\n".join(o) + "\n")
    print("millicode: %d words; handlers for %s" % (len(words), ", ".join(
        "%s (%d opwords)" % kv for kv in sorted(covered.items()))))


if __name__ == "__main__":
    main()

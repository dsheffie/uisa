#!/usr/bin/env python3
"""Assemble the millicode (millicode/*.s, *.c) and build its dispatch table.

C sources are compiled by ucc (build/compiler/ucc, see compiler/) into
build/millicode/<name>.s first; hand-written and compiled code are then
assembled together as one image.

Writes build/uisa_millicode.inc for the shadow model:
  MC_BASE            hidden-memory address of the image
  MC_IMAGE[]         the assembled words
  MC_ENTRY[65536]    per opword: byte offset of its routine, or -1
  MC_EP_<NAME>       byte offset of each spec entry point's routine, or -1
"""

import os
import re
import subprocess
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import flows  # noqa: E402
import m68kdec  # noqa: E402
import uisa  # noqa: E402

ROOT = os.path.join(HERE, "..")
UCC = os.path.join(ROOT, "build", "compiler", "ucc")
# -O0 (default, debug builds): greedy register allocation; -O2 (deploy
# builds, `make release`): the z3 search. Set with UCCFLAGS.
UCCFLAGS = os.environ.get("UCCFLAGS", "-O0").split()


def source_text(src):
    path = os.path.join(ROOT, "millicode", src)
    if src.endswith(".c"):
        out_dir = os.path.join(ROOT, "build", "millicode")
        os.makedirs(out_dir, exist_ok=True)
        out = os.path.join(out_dir, os.path.splitext(src)[0] + ".s")
        if subprocess.call([UCC] + UCCFLAGS + [path, "-o", out]) != 0:
            sys.exit("millicode: ucc failed on %s" % src)
        path = out
    with open(path) as f:
        return f.read()


def check_labels(texts):
    """The assembler lets a later label silently replace an earlier one."""
    seen = {}
    for src, text in texts:
        for line in text.splitlines():
            m = re.match(r"^\s*([A-Za-z_][\w.]*):", line.split(";")[0])
            if m:
                if m.group(1) in seen:
                    sys.exit("millicode: label %s defined in both %s and %s" % (m.group(1), seen[m.group(1)], src))
                seen[m.group(1)] = src


def main():
    with open(os.path.join(ROOT, "millicode", "dispatch.yaml")) as f:
        d = yaml.safe_load(f)
    texts = [(src, source_text(src)) for src in d["sources"]]
    check_labels(texts)
    text = "".join(t + "\n" for _, t in texts)
    spec = uisa.load()
    base = int(d.get("base", 0))
    words, labels = spec.assemble_program(text, base)
    ex = flows.Expander()
    entry = [-1] * 65536
    covered = {}
    for op in range(65536):
        fl = ex.expand(op)
        if fl.kind != "millicode":
            continue
        label = d["handlers"].get(fl.note)
        if label is None:
            continue
        if label not in labels:
            sys.exit("dispatch: no label %r" % label)
        entry[op] = labels[label] - base
        covered[fl.note] = covered.get(fl.note, 0) + 1
    o = ["// Generated by tools/gen_millicode.py from millicode/. Do not edit.",
         "static const uint32_t MC_BASE = 0x%x;" % base,
         "static const uint32_t MC_IMAGE[%d] = {" % len(words)]
    for i in range(0, len(words), 8):
        o.append("  " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    o.append("};")
    o.append("static const int32_t MC_ENTRY[65536] = {")
    for i in range(0, 65536, 32):
        o.append("  " + ",".join(str(x) for x in entry[i:i + 32]) + ",")
    o.append("};")
    eps = {e["name"] for e in spec.d["entry_points"]}
    for name, label in (d.get("entries") or {}).items():
        if name not in eps:
            sys.exit("dispatch: %r is not a spec entry point" % name)
        if label not in labels:
            sys.exit("dispatch: no label %r for entry %r" % (label, name))
        o.append("static const int32_t MC_EP_%s = %d;" % (name.upper(), labels[label] - base))
    with open(os.path.join(ROOT, "build", "uisa_millicode.inc"), "w") as f:
        f.write("\n".join(o) + "\n")
    print("millicode: %d words; handlers for %s" % (len(words), ", ".join(
        "%s (%d opwords)" % kv for kv in sorted(covered.items()))))


if __name__ == "__main__":
    main()

# Shared per-variant facts
# ---------------------------------------------------------------------------
def facts(spec, v):
    reads = spec.reads(v)
    return dict(
        reads_rs1=int("rs1" in reads), reads_rs2=int("rs2" in reads), reads_rd=int("rd" in reads),
        writes_rd=int(spec.writes_rd(v)),
        reads_nzvc=int("nzvc" in v.reads_flags), reads_x=int("x" in v.reads_flags),
        writes_nzvc=int("nzvc" in v.writes_flags), writes_x=int("x" in v.writes_flags),
        reads_u=int("u" in v.reads_flags), writes_u=int("u" in v.writes_flags),
        serialize=int(bool(v.serialize)), tied=int(bool(v.tied)),
        is_load=int(v.kind in ("load", "cas")), is_store=int(v.kind in ("store", "cas") or bool(v.attrs.get("store_bytes"))), is_probe=int(v.kind == "probe"),
        lock_begin=int(v.attrs.get("locked") == "begin"), lock_end=int(v.attrs.get("locked") == "end"),
        load_signed=int(bool(v.attrs.get("signed"))), mem_bytes=v.attrs.get("bytes") or v.attrs.get("store_bytes") or 0,
        unit=UNITS.index(v.unit), cti=CTIS.index(v.cti),
        gform=GFORMS.index(v.attrs.get("gform")), gfn=v.attrs.get("gfn", 0),
        gsize=spec.size_code.get(v.attrs.get("gsize"), 0) if v.kind == "guest" else 0,
        flags_on=int(bool(v.attrs.get("flags_on", False))),
        wb={None: 0, "pre": 1, "post": 2}[v.attrs.get("writeback")],
        # which register fields name FP registers: bit 0 rd, bit 1 rs1, bit 2 rs2
        fpregs=sum(1 << i for i, f in enumerate(("rd", "rs1", "rs2")) if f in spec.fp_fields(v)),
    )


def imm_sv(v, spec):
    """SystemVerilog expression for the decoded 32-bit immediate."""
    f = v.fmt.fields
    if "off" in f:
        return "{22'b0, insn[%d:%d], insn[%d:%d]}" % (f["wid"].hi, f["wid"].lo, f["off"].hi, f["off"].lo)
    if "imm" not in f:
        return "32'd0"
    fi = f["imm"]
    signed, scale = spec.imm_info(v)
    k = {1: 0, 4: 2}[scale]
    pad = 32 - fi.width - k
    body = "insn[%d:%d]" % (fi.hi, fi.lo)
    tail = (", %d'b0" % k) if k else ""
    ext = ("{%d{insn[%d]}}" % (pad, fi.hi)) if signed else ("%d'b0" % pad)
    return "{%s, %s%s}" % (ext, body, tail)



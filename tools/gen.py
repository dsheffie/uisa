def fixed_space(v):
    """The address space a variant's encoding fixes (its sp field is under the
    match mask), 0 without an sp field; None if the encoding leaves it free."""
    f = v.fmt.fields
    if "sp" not in f:
        return 0
    lo, w = f["sp"].lo, f["sp"].width
    m = ((1 << w) - 1) << lo
    if (v.mask & m) != m:
        return None
    return (v.match >> lo) & ((1 << w) - 1)


def sv_attrs(spec):
    """uisa_attrs(op): every attribute uisa_decode gives an op, from the op
    alone, for a decoder that has the fields (rd, rs1, rs2, imm) but no
    encoding (superdupersparc's C++ front end hands the core decoded fields).
    rd / rs1 / rs2 / imm and tie_violation (a function of rd and rs1) are left
    zero; valid is set for every op but UISA_ILLEGAL.  tests/tb_decode.sv
    checks it against uisa_decode for every variant's vector."""
    lines = ["  // the attributes of op, as uisa_decode gives them (fields and tie_violation zero)",
             "  function automatic uisa_dec_t uisa_attrs(input uisa_op_t op);",
             "    uisa_dec_t d;",
             "    d = '0;",
             "    unique case (op)"]
    for v in spec.variants:
        fa = facts(spec, v)
        body = ["d.op = %s;" % v.ident, "d.valid = 1'b1;"]
        sp = fixed_space(v)
        if sp is None:
            raise SystemExit("gen.py: %s: the address space is not a function of the op" % v.mnemonic)
        if sp:
            body.append("d.space = 2'd%d;" % sp)
        if "cond" in v.fixed:
            body.append("d.cond = 4'd%d;" % v.fixed["cond"])
        elif v.attrs.get("cond") is not None and v.unit == "alu":
            cc = [c["code"] for c in spec.guest_conds if c["name"] == v.cond][0]
            body.append("d.cond = 4'd%d;" % cc)
        for k in ("reads_rs1", "reads_rs2", "reads_rd", "writes_rd", "reads_nzvc", "reads_x",
                  "writes_nzvc", "writes_x", "reads_u", "writes_u", "serialize", "tied", "is_load", "is_store", "is_probe",
                  "lock_begin", "lock_end", "load_signed"):
            if fa[k]:
                body.append("d.%s = 1'b1;" % k)
        if fa["mem_bytes"]:
            body.append("d.mem_bytes = 3'd%d;" % fa["mem_bytes"])
        body.append("d.unit = 3'd%d;" % fa["unit"])
        if fa["cti"]:
            body.append("d.cti = 4'd%d;" % fa["cti"])
        if v.kind == "guest":
            body.append("d.gform = 3'd%d; d.gfn = 6'd%d; d.gsize = 2'd%d;" % (fa["gform"], fa["gfn"], fa["gsize"]))
        if fa["fpregs"]:
            body.append("d.fpregs = 3'd%d;" % fa["fpregs"])
        lines.append("      %s: begin" % v.ident)
        lines.append("        " + " ".join(body))
        lines.append("      end")
    lines.append("      default: d.op = UISA_ILLEGAL;")
    lines.append("    endcase")
    lines.append("    return d;")
    lines.append("  endfunction")
    return lines


def gen_sv(spec):
    vs = spec.variants
    lines = ["// " + HEADER, "package uisa_pkg;", ""]
    lines.append("  typedef enum logic [9:0] {")
    names = ["UISA_ILLEGAL"] + [v.ident for v in vs]
    for i, n in enumerate(names):
        lines.append("    %s = 10'd%d%s" % (n, i, "," if i + 1 < len(names) else ""))
    lines.append("  } uisa_op_t;")
    lines.append("")
    lines.append("  // unit: " + ", ".join("%d=%s" % (i, u) for i, u in enumerate(UNITS)))
    lines.append("  // cti:  " + ", ".join("%d=%s" % (i, c) for i, c in enumerate(CTIS)))
    lines.append("  // gform: " + ", ".join("%d=%s" % (i, c) for i, c in enumerate(GFORMS)))
    lines.append("  // gsize: 0=8, 1=16, 2=32.  space: " + ", ".join("%d=%s" % (s["code"], s["name"]) for s in spec.spaces))
    lines.append("""  typedef struct packed {
    uisa_op_t    op;
    logic        valid;
    logic [5:0]  rd, rs1, rs2;
    logic [31:0] imm;
    logic        reads_rs1, reads_rs2, reads_rd, writes_rd;
    logic        reads_nzvc, reads_x, writes_nzvc, writes_x;
    logic        reads_u, writes_u;   // millicode predicate u (probe .us/.ua, ld.c/st.c/stu.c, b.u/b.nu)
    logic        serialize, tied, tie_violation;
    logic        is_load, is_store, is_probe, lock_begin, lock_end, load_signed;
    logic [2:0]  mem_bytes;
    logic [1:0]  space;
    logic [3:0]  cond;
    logic [2:0]  unit;
    logic [3:0]  cti;
    logic [2:0]  gform;
    logic [5:0]  gfn;
    logic [1:0]  gsize;
    logic [2:0]  fpregs;   // the fields naming FP registers: bit 0 rd, bit 1 rs1, bit 2 rs2
  } uisa_dec_t;
""")
    lines.append("  function automatic uisa_dec_t uisa_decode(input logic [31:0] insn);")
    lines.append("    uisa_dec_t d;")
    lines.append("    d = '0;")
    lines.append("    unique casez (insn)")
    for v in vs:
        pat = "".join("?" if not (v.mask >> b) & 1 else str((v.match >> b) & 1) for b in range(31, -1, -1))
        fa = facts(spec, v)
        f = v.fmt.fields
        body = ["d.op = %s;" % v.ident, "d.valid = 1'b1;"]
        for reg in ("rd", "rs1", "rs2"):
            if reg in f:
                body.append("d.%s = insn[%d:%d];" % (reg, f[reg].hi, f[reg].lo))
        if "sp" in f:
            body.append("d.space = insn[%d:%d];" % (f["sp"].hi, f["sp"].lo))
        if "cond" in v.fixed:
            body.append("d.cond = 4'd%d;" % v.fixed["cond"])
        elif v.attrs.get("cond") is not None and v.unit == "alu":
            cc = [c["code"] for c in spec.guest_conds if c["name"] == v.cond][0]
            body.append("d.cond = 4'd%d;" % cc)
        body.append("d.imm = %s;" % imm_sv(v, spec))
        for k in ("reads_rs1", "reads_rs2", "reads_rd", "writes_rd", "reads_nzvc", "reads_x",
                  "writes_nzvc", "writes_x", "reads_u", "writes_u", "serialize", "tied", "is_load", "is_store", "is_probe",
                  "lock_begin", "lock_end", "load_signed"):
            if fa[k]:
                body.append("d.%s = 1'b1;" % k)
        if fa["mem_bytes"]:
            body.append("d.mem_bytes = 3'd%d;" % fa["mem_bytes"])
        body.append("d.unit = 3'd%d;" % fa["unit"])
        if fa["cti"]:
            body.append("d.cti = 4'd%d;" % fa["cti"])
        if v.kind == "guest":
            body.append("d.gform = 3'd%d; d.gfn = 6'd%d; d.gsize = 2'd%d;" % (fa["gform"], fa["gfn"], fa["gsize"]))
        if fa["fpregs"]:
            body.append("d.fpregs = 3'd%d;" % fa["fpregs"])
        if v.tied:
            body.append("d.tie_violation = (insn[%d:%d] != insn[%d:%d]);" % (f["rs1"].hi, f["rs1"].lo, f["rd"].hi, f["rd"].lo))
        lines.append("      32'b%s: begin // %s" % (pat, v.mnemonic))
        lines.append("        " + " ".join(body))
        lines.append("      end")
    lines.append("      default: d.op = UISA_ILLEGAL;")
    lines.append("    endcase")
    lines.append("    return d;")
    lines.append("  endfunction")
    lines.append("")
    lines += sv_attrs(spec)
    lines.append("")
    lines.append("endpackage")
    write("uisa_pkg.sv", "\n".join(lines) + "\n")



def md_escape(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def gen_doc(spec):
    d = spec.d
    with open(os.path.join(ROOT, "doc", "intro.md")) as f:
        out = [f.read().rstrip(), ""]
    out.append("<!-- Everything below is generated from spec/uisa.yaml by tools/gen.py. -->")
    out.append("")
    out.append("# Reference (generated)")
    out.append("")
    out.append("Spec version **%s**. %d concrete instruction variants." % (d["version"], len(spec.variants)))
    out.append("")

    out.append("## Parameters")
    out.append("")
    out.append("| Parameter | Value |")
    out.append("|---|---|")
    for k, v in d["params"].items():
        out.append("| `%s` | %s |" % (k, v))
    out.append("")

    out.append("## Register namespace")
    out.append("")
    out.append("Register specifiers are %d bits. Indices not listed are reserved." % d["params"]["reg_spec_bits"])
    out.append("")
    out.append("| Index | Names | Description |")
    out.append("|---|---|---|")
    for c in d["reg_classes"]:
        if "prefix" in c:
            rng = "%d-%d" % (c["base"], c["base"] + c["count"] - 1)
            names = "`%s0`-`%s%d`" % (c["prefix"], c["prefix"], c["count"] - 1)
        else:
            rng, names = str(c["base"]), "`%s`" % c["name"]
        out.append("| %s | %s | %s |" % (rng, names, md_escape(c["desc"])))
    out.append("")
    if d.get("fp_regs"):
        out.append("FP registers are a namespace of their own, 64 bits each, named only by the register "
                   "fields an FP op lists as FP (the Operands column marks them `f:`):")
        out.append("")
        out.append("| Index | Names | Description |")
        out.append("|---|---|---|")
        for c in d["fp_regs"]:
            out.append("| %d-%d | `%s%d`-`%s%d` | %s |" % (c["base"], c["base"] + c["count"] - 1, c["prefix"], c["base"],
                                                       c["prefix"], c["base"] + c["count"] - 1, md_escape(c["desc"])))
        out.append("")

    out.append("## Flags")
    out.append("")
    out.append("%d renamed flag resources: " % len(d["flags"]) + ", ".join("`%s` (%s)" % (f["name"], " ".join(f["bits"])) for f in d["flags"]) + ".")
    out.append("`rdccr`/`wrccr` use the 68k CCR layout: " + ", ".join("%s=bit %d" % (k, v) for k, v in d["ccr_layout"].items()) + ".")
    priv = [f["name"] for f in d["flags"] if not any(b in d["ccr_layout"] for b in f["bits"])]
    if priv:
        out.append("%s: the millicode-private predicate, never guest-visible and not in the CCR layout "
                   "(`rdccr`/`wrccr` do not touch it). Probes `.us`/`.ua` write it (the probed access would "
                   "succeed: `%s`, from the MMUSR result `mmusr`, `w` for a write probe, `user` for a user-mode "
                   "access and `tce` for TC.E: with translation off and no TTR match the MMUSR is 0 and the access "
                   "succeeds); `ld.c`, `st.c`, `stu.c`, `b.u` and `b.nu` "
                   "read it." % (", ".join("`%s`" % n for n in priv), d["probe_ok"]))
    out.append("")

    out.append("## Formats")
    out.append("")
    out.append("| Format | Fields (msb to lsb) | Immediate |")
    out.append("|---|---|---|")
    for name, fd in d["formats"].items():
        fl = " ".join("`%s[%d:%d]`" % (f[0], f[1], f[2]) for f in fd["fields"])
        fmt = spec.formats[name]
        imm = ("signed" if fmt.imm_signed else "unsigned") + (", x%d" % fmt.imm_scale if fmt.imm_scale != 1 else "") if "imm" in fmt.fields else ""
        out.append("| %s | %s | %s |" % (name, fl, imm))
    out.append("")
    out.append("Base ops can override immediate signedness (e.g. logical immediates are zero-extended).")
    out.append("")

    out.append("## Major opcode map")
    out.append("")
    inv = {v: k for k, v in spec.majors.items()}
    out.append("| | +0 | +1 | +2 | +3 | +4 | +5 | +6 | +7 |")
    out.append("|---|---|---|---|---|---|---|---|---|")
    for row in range(8):
        cells = []
        for col in range(8):
            n = row * 8 + col
            cells.append(inv.get(n, "*FP*" if 49 <= n <= 52 else "-"))
        out.append("| **%d** | %s |" % (row * 8, " | ".join(cells)))
    out.append("")

    out.append("## Base operations")
    out.append("")
    out.append("No flags, full 32-bit results, unless the row says otherwise. Operand names: `a` = rs1, `b` = rs2 or the decoded immediate.")
    out.append("")
    out.append("| Mnemonic | Format | Encoding | Operands | Semantics | Notes |")
    out.append("|---|---|---|---|---|---|")
    for op in d["base_ops"]:
        if "family" in op:
            conds = d["guest_conds"] if op["per_cond"] == "guest" else d["base_conds"]
            mn = "`%s.<cc>`" % op["family"]
            enc = "%s %s" % (op["major"], ("fn=0x%02x+cc" % op["fn_base"]) if "fn_base" in op else "cond=cc")
            note = op.get("desc", "") + " cc: " + " ".join(c["name"] for c in conds) + "."
        else:
            mn = "`%s`" % op["name"]
            enc = op["major"] + ((" fn=%d" % op["fn"]) if "fn" in op else "") + ((" cond=%d" % op["cond"]) if "cond" in op else "")
            note = " ".join(x for x in (op.get("desc", ""), op.get("note", "")) if x)
        extra = []
        if op.get("reads_flags"):
            extra.append("reads " + "+".join(op["reads_flags"]))
        if op.get("writes_flags"):
            extra.append("writes " + "+".join(op["writes_flags"]))
        if op.get("serialize"):
            extra.append("serializes")
        if extra:
            note = (note + " (" + ", ".join(extra) + ")").strip()
        sem = "`%s`" % md_escape(op["sem"]) if op.get("sem") else ""
        asm = ", ".join(("f:" + a) if a in op.get("fp", []) else a for a in op["asm"])
        out.append("| %s | %s | %s | %s | %s | %s |" % (mn, op["fmt"], enc, asm, sem, md_escape(note)))
    out.append("")

    out.append("## Guest-semantic operations")
    out.append("")
    out.append("Each family expands into sized forms (see *Sized operations* above). `<f>.8`/`<f>.16` merge into rd "
               "and are two-address (rs1 = rd); `<f>.32` is three-address; `<f>.8z`/`<f>.16z` zero-fill and do not "
               "read the old rd. Families marked *imm* also have `<f>i.<sz>[z]` forms with a 6-bit unsigned immediate. "
               "Every form has a `.nf` variant that writes no flags.")
    out.append("")
    out.append("| Family | fn | Kind | Sizes | imm | Reads | Writes | Notes |")
    out.append("|---|---|---|---|---|---|---|---|")
    for op in d["guest_ops"]:
        notes = " ".join(x for x in (op.get("desc", ""), ("Precondition: " + op["precondition"]) if op.get("precondition") else "",
                                     ("Trap: " + op["trap"]) if op.get("trap") else "") if x)
        out.append("| `%s` | %d | %s | %s | %s | %s | %s | %s |" % (
            op["name"], op["fn"], op["kind"], ",".join(str(s) for s in op.get("sizes", [8, 16, 32])),
            "yes" if op.get("imm") else "", " ".join(op.get("reads", [])) or "-",
            " ".join(op.get("writes", [])), md_escape(notes)))
    out.append("")
    out.append("### Guest-op semantics")
    out.append("")
    out.append("C reference semantics, exactly as compiled into the generated ISS header. "
               "`n` = operand width, `m` = MSK(n), `xin`..`cin` = incoming flags. "
               "Setting `T` to a vector flags a trap: the uop's instruction retires (its other results, such as an "
               "address-register update, stand) and the exception is then taken with the next PC stacked, as the "
               "68k does for a zero divide.")
    out.append("")
    for op in d["guest_ops"]:
        out.append("**`%s`**" % op["name"])
        out.append("")
        out.append("```c")
        out.append(op["sem"].strip())
        out.append("```")
        out.append("")

    out.append("## Conditions")
    out.append("")
    out.append("| Code | Guest (`bcc`, `sel`, `s`) | Expression | Base (`b`) | Expression |")
    out.append("|---|---|---|---|---|")
    # BR cond codes the base conditions leave free carry explicit branches (b.u, b.nu)
    br_ops = {o["cond"]: o for o in d["base_ops"] if o.get("major") == "BR" and "cond" in o}
    for c in d["guest_conds"]:
        b = [x for x in d["base_conds"] if x["code"] == c["code"]]
        bn, be = (b[0]["name"], "`%s`" % b[0]["expr"]) if b else ("", "")
        if not b and c["code"] in br_ops:
            o = br_ops[c["code"]]
            bn, be = o["name"].split(".", 1)[1], "`%s` (the `%s` op)" % (o["sem"], o["name"])
        out.append("| %d | `%s` | `%s` | %s | %s |" % (c["code"], c["name"], c["expr"], ("`%s`" % bn) if bn else "", be))
    out.append("")

    out.append("## Memory operations")
    out.append("")
    out.append("Mnemonic suffix selects the address space: " + ", ".join("`.%s` %s" % (s["suffix"], s["name"]) for s in d["spaces"]) + ".")
    out.append("Syntax: `ld.32.gd rd, disp(rs1)`; stores take the data register in the rd position.")
    out.append("")
    out.append("| Space | Code | Description |")
    out.append("|---|---|---|")
    for s in d["spaces"]:
        out.append("| `.%s` | %d | %s |" % (s["suffix"], s["code"], md_escape(s["desc"])))
    out.append("")
    out.append("| Op | Major | Kind | Bytes | Notes |")
    out.append("|---|---|---|---|---|")
    for op in d["mem_ops"]:
        kind = op["kind"] + (" (signed)" if op.get("signed") else "") + ((" lock-" + op["locked"]) if op.get("locked") else "")
        if op.get("reads_flags"):
            kind += ", reads " + "+".join(op["reads_flags"])

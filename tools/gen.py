BUILD = os.path.join(ROOT, "build")

UNITS = ["alu", "mul", "div", "mem", "br", "sys", "fpu"]
CTIS = [None, "branch", "jump", "jump_ind", "call", "ret", "gexit", "gfault", "gbranch", "gjump"]
GFORMS = [None, "merge", "zfill", "full32", "compare", "full", "tiedfull"]
HEADER = "Generated by tools/gen.py from spec/uisa.yaml. Do not edit."


def write(name, text, outdir=BUILD):
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, name), "w") as f:
        f.write(text)


